"""benchtruth.db — load the parts database, signal profiles and board profiles.

The parts DB is curated ground truth: every entry carries a source, a dated price
band, and a measurement confidence. Nothing in here is generated by a model.
"""
from __future__ import annotations

import json
import pathlib
from typing import Any, Optional

ROOT = pathlib.Path(__file__).resolve().parent.parent
PARTS_DB = ROOT / "parts" / "parts_db.json"
SIGNAL_PROFILES = ROOT / "parts" / "signal_profiles.json"


class DbError(Exception):
    pass


class Db:
    def __init__(self, parts_db: dict, profiles: dict):
        self.raw = parts_db
        self.profiles = profiles
        self.version = parts_db.get("db_version", "0")
        self._parts = {p["id"]: p for p in parts_db.get("parts", [])}
        self._boards = {b["id"]: b for b in parts_db.get("boards", [])}
        self._consumables = {c["id"]: c for c in parts_db.get("consumables", [])}

    # ---- lookups -------------------------------------------------------
    def part(self, part_id: str) -> Optional[dict]:
        return self._parts.get(part_id)

    def board(self, board_id: str) -> dict:
        if board_id not in self._boards:
            raise DbError(f"unknown board: {board_id}")
        return self._boards[board_id]

    def profile(self, part_id: str) -> dict:
        return self.profiles.get(part_id, {})

    def has_part(self, part_id: str) -> bool:
        return part_id in self._parts

    def price_band(self, part_id: str) -> Optional[tuple]:
        """(min_idr, max_idr) for a part or consumable, or None."""
        rec = self._parts.get(part_id) or self._consumables.get(part_id)
        if not rec:
            return None
        lo = rec.get("price_idr_min")
        hi = rec.get("price_idr_max")
        if lo is None or hi is None:
            return None
        return (int(lo), int(hi))

    def find_by_keyword(self, needle: str) -> Optional[str]:
        """Loose lookup used by the offline fallback parser."""
        needle = needle.lower()
        for pid, prof in self.profiles.items():
            for kw in prof.get("keywords", []):
                if needle in kw.lower() or kw.lower() in needle:
                    return pid
        for pid, rec in self._parts.items():
            if needle in rec.get("name", "").lower():
                return pid
        return None


def _read_json(path: pathlib.Path) -> dict:
    if not path.exists():
        raise DbError(f"missing file: {path}")
    with path.open(encoding="utf-8") as fh:
        return json.load(fh)


def load_db(parts_db_path=PARTS_DB, profiles_path=SIGNAL_PROFILES) -> Db:
    return Db(_read_json(parts_db_path), _read_json(profiles_path))
